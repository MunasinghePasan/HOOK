import { existsSync, readFileSync } from "node:fs";
import { email, instagram } from "../shared/inquiry.mjs";

const logoFile = new URL("../public/images/hook-logo.jpeg", import.meta.url);
const logo = readFileSync(
  existsSync(logoFile)
    ? logoFile
    : new URL("../dist/images/hook-logo.jpeg", import.meta.url),
);
const logoCid = "hook-logo@hook.website";
const linkedin = "https://www.linkedin.com/company/hookbysemicolon/";
const escape = (value) =>
  value.replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        char
      ],
  );
const paragraph = (text) =>
  '<p style="margin:0 0 16px;line-height:1.65">' +
  escape(text).replace(/\r?\n/g, "<br>") +
  "</p>";
const smallLabel =
  "font-size:12px;line-height:18px;font-weight:bold;color:#48667d";
const linkStyle = "color:#164f80;text-decoration:underline";

function layout(title, content, footer) {
  return `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head>
<body style="margin:0;background:#edf4f8;color:#16344d;font-family:Arial,Helvetica,sans-serif">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" bgcolor="#edf4f8"><tr><td align="center" style="padding:24px 8px">
<!--[if mso]><table role="presentation" width="580"><tr><td><![endif]-->
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" bgcolor="#ffffff" style="max-width:580px;border:1px solid #d9e5ed;border-top:5px solid #15364f;border-collapse:collapse;text-align:left">
<tr><td style="padding:20px 24px"><img src="cid:${logoCid}" width="124" height="71" alt="HOOK" style="display:block;border:0"></td></tr>
<tr><td bgcolor="#eef6fc" style="padding:20px 24px;border-top:1px solid #dce9f1;border-bottom:1px solid #dce9f1"><h1 style="margin:0;font-size:25px;line-height:1.25;color:#14344f">${title}</h1></td></tr>
<tr><td style="padding:24px;font-size:15px;line-height:1.6;word-break:break-word">${content}</td></tr>
<tr><td bgcolor="#f4f8fb" style="padding:18px 24px;border-top:1px solid #dce9f1;font-size:13px;line-height:1.65;color:#48667d">${footer}</td></tr>
</table><!--[if mso]></td></tr></table><![endif]--></td></tr></table></body></html>`;
}

export function messages(fields, config, now = new Date()) {
  const stamp =
    new Intl.DateTimeFormat("en-GB", {
      dateStyle: "long",
      timeStyle: "short",
      timeZone: "Asia/Colombo",
    }).format(now) + " (Asia/Colombo)";
  const contactRows = [
    ["Full Name", fields.name],
    ["Email Address", fields.email],
    ["Contact Number", fields.phone],
  ];
  const intro = "A new inquiry has been submitted through the HOOK website.";
  const footer =
    "This notification was automatically generated by the HOOK website inquiry system.";
  const details = contactRows
    .map(
      ([label, value]) =>
        `<tr><td style="border-bottom:1px solid #e0eaf0;padding:9px 14px"><strong style="${smallLabel}">${label}</strong><br>${escape(value)}</td></tr>`,
    )
    .join("");
  const adminBody =
    paragraph(intro) +
    `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border:1px solid #dce7ef">${details}</table>
    <h2 style="font-size:17px;line-height:1.4;margin:22px 0 8px">Inquiry Description</h2>
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0"><tr><td bgcolor="#f1f7fb" style="padding:14px;border-left:3px solid #78a8c8">${escape(fields.description).replace(/\r?\n/g, "<br>")}</td></tr></table>
    <p style="margin:18px 0 0;font-size:13px;color:#48667d"><strong>Submitted At</strong><br>${stamp}</p>`;
  const greeting = "Hi " + fields.name + ",";
  const paragraphs = [
    greeting,
    "Thank you for reaching out to HOOK!",
    "We've successfully received your inquiry, and our team will review your message.",
    "We'll get back to you as soon as possible.",
    "We appreciate your interest in HOOK.",
  ];
  const closing = "Best regards,\nThe HOOK Team";
  const slogan = "Find Your Next Opportunity Here.";
  const acknowledgementBody =
    paragraphs.map(paragraph).join("") +
    '<p style="margin:20px 0 0;line-height:1.6">Best regards,<br><strong>The HOOK Team</strong></p>';
  const contactFooter = `<strong style="color:#15364f">${slogan}</strong><br>
    <a href="mailto:${email}" style="${linkStyle}">${email}</a><br>
    <a href="${instagram}" style="${linkStyle}">Instagram</a> &nbsp;·&nbsp; <a href="${linkedin}" style="${linkStyle}">LinkedIn</a>`;
  const common = {
    from: config.user,
    attachments: [
      {
        filename: "hook-logo.jpeg",
        content: logo,
        contentType: "image/jpeg",
        contentDisposition: "inline",
        cid: logoCid,
      },
    ],
  };
  return {
    admin: {
      ...common,
      to: config.receiver,
      replyTo: fields.email,
      subject: "[HOOK] New Website Inquiry | " + fields.name,
      text: [
        "HOOK | New Website Inquiry",
        intro,
        ...contactRows.map(([key, value]) => key + ": " + value),
        "Inquiry Description: " + fields.description,
        "Submitted At: " + stamp,
        footer,
      ].join("\n\n"),
      html: layout("New Website Inquiry", adminBody, footer),
    },
    acknowledgement: {
      ...common,
      to: fields.email,
      replyTo: email,
      subject: "We've Received Your Inquiry | HOOK",
      text: [
        "Thank You for Reaching Out!",
        ...paragraphs,
        closing,
        slogan,
        email,
        instagram,
        linkedin,
      ].join("\n\n"),
      html: layout(
        "Thank You for Reaching Out!",
        acknowledgementBody,
        contactFooter,
      ),
    },
  };
}
